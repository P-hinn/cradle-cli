function colophon(input: ReportInput): string {
  return `<footer class="colophon">
<p><strong>This is a technical snapshot, not legal advice.</strong> ${escapeHtml(input.toolName)} documents which components a project ships and which advisories were public for them at the time of the scan. It is not a conformity assessment, not a declaration of conformity, and it does not certify compliance with any regulation.</p>
<p>Findings reflect the advisory databases aggregated by OSV.dev as of ${escapeHtml(formatTimestamp(input.timestamp))}. Advisories are published continuously, so an empty result means "nothing was known then", not "nothing exists".</p>
<p>The machine-readable data behind this page is embedded in it, in the <code>application/json</code> block below, alongside the CycloneDX SBOM written next to this file.</p>
</footer>`
}

/**
 * The same data the page renders, embedded verbatim so the report can be parsed
 * as well as read. A reviewer who receives only this file still has everything.
 */
function dataBlock(input: ReportInput): string {
  return `<script type="application/json" id="cradle-data">
${embedJson({
  tool: { name: input.toolName, version: input.toolVersion },
  project: { name: input.graph.root.name, version: input.graph.root.version },
  timestamp: input.timestamp,
  packageManager: input.graph.packageManager,
  scope: input.graph.includeDev ? 'all' : 'production',
  offline: input.offline,
  sbom: { specVersion: input.specVersion, serialNumber: input.serialNumber },
  components: input.graph.components,
  findings: input.findings,
  suppressed: input.suppressed ?? [],
  readiness: input.readiness ?? null,
})}
</script>`
}

// ---------------------------------------------------------------------------
// Small shared helpers
// ---------------------------------------------------------------------------

function severityMark(severity: Severity): string {
  return `<span class="sev sev-${severity}" data-glyph="${escapeHtml(SEVERITY_GLYPH[severity])}">${escapeHtml(severity)}</span>`
}

function licenceLabel(licenses: readonly ResolvedLicense[]): string {
  if (licenses.length === 0) return 'undeclared'
  return licenses
    .map((license) => {
      if (license.kind === 'id') return license.id
      if (license.kind === 'expression') return license.expression
      return license.name
    })
    .join(', ')
}

/** UTC, spelled out. A report read in another timezone must not shift its date. */
function formatTimestamp(iso: string): string {
  const date = new Date(iso)
  if (Number.isNaN(date.getTime())) return iso
  return `${date.toISOString().replace('T', ' ').slice(0, 19)} UTC`
}

function formatDate(iso: string): string {
  const date = new Date(iso)
  return Number.isNaN(date.getTime()) ? iso : date.toISOString().slice(0, 10)
}
