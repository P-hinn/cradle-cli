function componentsSection(graph: DependencyGraph): string {
  if (graph.components.length === 0) {
    return `<h2>Components</h2><div class="empty">No dependencies were resolved.</div>`
  }

  return `<h2>Components <span class="count">${graph.components.length}</span></h2>
<div class="controls" data-controls="components" hidden>
  <input type="search" data-filter="text" placeholder="Filter by name, version, or licence" aria-label="Filter components">
  <label><input type="checkbox" data-facet="relationship" value="direct"> direct only</label>
  <label><input type="checkbox" data-facet="licence" value="unknown"> undeclared licence</label>
  <span class="spacer"></span>
  <span class="result-count" data-result-count aria-live="polite"></span>
</div>
<div class="scroll"><table data-table="components">
<thead><tr>
  <th data-sort="name">Name</th>
  <th data-sort="version">Version</th>
  <th data-sort="licence">Licence</th>
  <th data-sort="relationship">Relationship</th>
</tr></thead>
<tbody>
${graph.components.map(componentRow).join('\n')}
</tbody>
</table></div>`
}

function componentRow(component: ResolvedComponent): string {
  const licence = component.licenseUnknown ? 'undeclared' : licenceLabel(component.licenses)
  const haystack = `${component.name} ${component.version} ${licence}`.toLowerCase()
  const relationship = component.direct ? 'direct' : 'transitive'

  const tags = [
    component.workspace ? '<span class="tag">workspace</span>' : '',
    component.dev ? '<span class="tag">dev</span>' : '',
  ]
    .filter((tag) => tag !== '')
    .join(' ')

  return `  <tr data-search="${escapeHtml(haystack)}" data-relationship="${relationship}" data-licence="${component.licenseUnknown ? 'unknown' : 'known'}" data-sort-name="${escapeHtml(component.name)}" data-sort-version="${escapeHtml(component.version)}" data-sort-licence="${escapeHtml(licence)}" data-sort-relationship="${relationship}">
    <td><code>${escapeHtml(component.name)}</code>${tags === '' ? '' : ` ${tags}`}</td>
    <td class="mono">${escapeHtml(component.version)}</td>
    <td>${component.licenseUnknown ? '<em>undeclared</em>' : `<code>${escapeHtml(licence)}</code>`}</td>
    <td>${relationship}</td>
  </tr>`
}

