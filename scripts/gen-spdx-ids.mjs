/**
 * Generates src/core/sbom/spdx-ids.generated.ts from the vendored CycloneDX
 * SPDX schema, so license IDs can be validated at runtime without reading any
 * file. Re-run after updating schema/spdx.schema.json:
 *
 *   node scripts/gen-spdx-ids.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'

const schemaPath = new URL('../schema/spdx.schema.json', import.meta.url)
const outPath = new URL('../src/core/sbom/spdx-ids.generated.ts', import.meta.url)

const { enum: ids } = JSON.parse(readFileSync(schemaPath, 'utf8'))
if (!Array.isArray(ids) || ids.length === 0) {
  throw new Error('schema/spdx.schema.json has no enum of license IDs')
}

const body = ids.map((id) => `  '${id.replace(/'/g, "\\'")}',`).join('\n')
writeFileSync(
  outPath,
  `// Generated by scripts/gen-spdx-ids.mjs from schema/spdx.schema.json. Do not edit.
// ${ids.length} identifiers, matching the SPDX enum CycloneDX validates against.

export const SPDX_LICENSE_IDS: ReadonlySet<string> = new Set([
${body}
])
`,
)
console.log(`wrote ${ids.length} SPDX identifiers`)
